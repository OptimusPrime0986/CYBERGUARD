"""Deterministic config rendering. Inputs are pre-validated (strict charsets), never raw user text."""
import json
from datetime import datetime, timezone

LISTEN = 8000          # public HTTP listener inside the proxy container
TLS_LISTEN = 8443      # public HTTPS listener
STATE_LISTEN = 9000    # internal-only state listener (NOT published)
ENGINE = {"blocking": "On", "monitoring": "DetectionOnly"}
HEADERS = (("X-Content-Type-Options", "nosniff"), ("X-Frame-Options", "SAMEORIGIN"),
           ("Referrer-Policy", "strict-origin-when-cross-origin"), ("Permissions-Policy", "geolocation=(), camera=(), microphone=()"))
HSTS = "max-age=31536000; includeSubDomains"
GENERIC = {500: "Something went wrong", 502: "Service temporarily unavailable", 503: "Service temporarily unavailable", 504: "The service took too long to respond"}


def tls_dir(root, sid):
    return f"{root}/tls/{sid}"


def render_release(release_id, root, entries, setup_include=None, tls_sites=frozenset(), trusted_proxies=(), https_port=443, today=None):
    """entries: {site_id: (Site, Policy, policy_version)} -> {relative_path: content}"""
    today = today or datetime.now(timezone.utc).strftime("%Y-%m-%d")
    live = {sid for sid in entries if sid in tls_sites and entries[sid][1].https != "off"}
    f = {"nginx/00-default.conf": _default(release_id, root, sorted(live))}
    zones = [f"limit_req_zone $binary_remote_addr zone=cg_{sid}_{r['name']}:2m rate={r['per_minute']}r/m;"
             for sid in sorted(entries) for r in entries[sid][1].rate_limits]
    f["nginx/05-ratelimit.conf"] = "# rate-limit zones (one per site rule, 2 MB each)\n" + "\n".join(zones) + "\n"
    manifest, state_locs = {"release": release_id, "sites": {}}, []
    for sid in sorted(entries):
        site, pol, ver = entries[sid]
        tls = sid in live
        manifest["sites"][sid] = {"hostname": site.hostname, "policy_version": ver, "mode": pol.mode, "https": pol.https if tls else "off"}
        f[f"nginx/10-site-{sid}.conf"] = _site(release_id, root, site, pol, ver, tls, trusted_proxies, https_port)
        if pol.mode != "disabled":
            f[f"modsec/{sid}.conf"] = _modsec(sid, pol, ver, release_id, setup_include, today)
        body = json.dumps({"site": sid, "policy_version": ver, "mode": pol.mode, "release": release_id})
        state_locs.append(f"    location = /state/{sid} {{ default_type application/json; return 200 '{body}'; }}")
    f["nginx/99-state.conf"] = f"server {{\n    listen {STATE_LISTEN};\n" + "\n".join(state_locs) + "\n    location / { return 404; }\n}\n"
    f["manifest.json"] = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return f


def _default(release_id, root, live):
    s = (f"# generated by CyberGuard release {release_id}\n# (server_tokens is already set to 'off' by the image's own conf.d/default.conf; setting it again is a duplicate-directive error)\n"
         "log_format cyberguard escape=json '{\"t\":\"$time_iso8601\",\"host\":\"$host\",\"site\":\"$cg_site\",\"ver\":\"$cg_ver\",\"mode\":\"$cg_mode\","
         "\"rid\":\"$request_id\",\"method\":\"$request_method\",\"uri\":\"$uri\",\"status\":$status,\"up\":\"$upstream_status\",\"rt\":\"$request_time\",\"ip\":\"$remote_addr\"}';\n"
         "access_log /var/log/nginx/cyberguard.jsonl cyberguard;\n"
         f"server {{ listen {LISTEN} default_server; server_name _; set $cg_site \"-\"; set $cg_ver \"0\"; set $cg_mode \"none\"; return 444; }}\n")
    if live:   # unknown Host on the HTTPS port: complete the handshake with a real cert, then drop the request
        s += (f"server {{ listen {TLS_LISTEN} ssl default_server; server_name _; ssl_certificate {tls_dir(root, live[0])}/fullchain.pem; "
              f"ssl_certificate_key {tls_dir(root, live[0])}/privkey.pem; ssl_protocols TLSv1.2 TLSv1.3; "
              "set $cg_site \"-\"; set $cg_ver \"0\"; set $cg_mode \"none\"; return 444; }\n")
    return s


def _modsec(sid, pol, ver, release_id, setup_include, today):
    L = [f"# site {sid} policy v{ver} release {release_id}",
         "# Overrides only. The image already loads the CRS globally in nginx.conf; loading it again fails with 'Rule id ... is duplicated'."]
    if setup_include: L.append(f"Include {setup_include}")
    L.append(f'SecAction "id:1000900,phase:1,pass,nolog,setvar:tx.inbound_anomaly_score_threshold={pol.anomaly_threshold},'
             f'setvar:tx.blocking_paranoia_level={pol.paranoia_level},setvar:tx.detection_paranoia_level={pol.paranoia_level}"')
    n = 1001000
    for e in pol.exclusions:
        if e.get("expires") and e["expires"] < today: continue          # expired: no longer applied
        ctl = (f"ctl:ruleRemoveTargetById={e['rule_id']};{e['target']}" if e.get("target") else f"ctl:ruleRemoveById={e['rule_id']}")
        cond = f'"@beginsWith {e["path"]}"' if e.get("path") else '"@unconditionalMatch"'
        L.append(f'SecRule REQUEST_URI {cond} "id:{n},phase:1,pass,nolog,{ctl}"'); n += 1
    L += [f"SecRuleEngine {ENGINE[pol.mode]}", f"SecRequestBodyLimit {pol.max_body_bytes}",
          f"SecRequestBodyNoFilesLimit {min(pol.max_body_bytes, 131072)}",
          f"SecResponseBodyAccess {'On' if pol.inspect_responses else 'Off'}"]
    return "\n".join(L) + "\n"


def _proxy(site, pol):
    L = [f"proxy_pass {site.origin_scheme}://{site.origin_host}:{site.origin_port};", "proxy_set_header Host $host;",
         "proxy_set_header X-Request-ID $request_id;",
         "proxy_set_header X-Forwarded-For $remote_addr;   # overwritten, never appended (real-IP handling below)",
         "proxy_set_header X-Forwarded-Proto $scheme;", "proxy_hide_header X-Powered-By;"]
    if pol.security_headers: L += [f"proxy_hide_header {h};" for h, _ in HEADERS]
    if pol.generic_errors: L.append("proxy_intercept_errors on;")
    if site.origin_scheme == "https":
        L += ["proxy_ssl_server_name on;", f"proxy_ssl_name {site.origin_host};", "proxy_ssl_protocols TLSv1.2 TLSv1.3;"]
        L += (["proxy_ssl_verify on;", "proxy_ssl_trusted_certificate /etc/ssl/certs/ca-certificates.crt;"] if site.tls_verify
              else ["proxy_ssl_verify off;   # explicitly permitted by admin policy"])
    return L


def _server(release_id, root, site, pol, ver, tls, trusted, https_port, redirect=False):
    sid = site.site_id
    L = ["server {", f"    listen {TLS_LISTEN} ssl;" if tls else f"    listen {LISTEN};", f"    server_name {' '.join(site.allowed_hostnames)};"]
    if tls:
        d = tls_dir(root, sid)
        L += [f"    ssl_certificate {d}/fullchain.pem;", f"    ssl_certificate_key {d}/privkey.pem;", "    ssl_protocols TLSv1.2 TLSv1.3;",
              "    ssl_session_cache shared:cg_ssl:10m;", "    ssl_session_timeout 1h;", "    ssl_session_tickets off;"]
    if trusted:
        L += [f"    set_real_ip_from {c};" for c in trusted] + ["    real_ip_header X-Forwarded-For;", "    real_ip_recursive on;"]
    L += [f'    set $cg_site "{sid}"; set $cg_ver "{ver}"; set $cg_mode "{pol.mode}";', f"    client_max_body_size {pol.max_body_bytes};",
          f"    if ($request_method !~ ^({'|'.join(pol.allowed_methods)})$) {{ return 405; }}"]
    if redirect:
        port = "" if https_port == 443 else f":{https_port}"
        return "\n".join(L + [f"    return 301 https://$host{port}$request_uri;", "}"])
    if pol.mode == "disabled":
        L.append("    modsecurity off;   # WAF disabled for THIS site only; proxy path, limits and hardening stay")
    else:
        L += ["    modsecurity on;", '    modsecurity_transaction_id "$request_id";   # audit-log id == access-log id',
              f"    modsecurity_rules_file {root}/releases/{release_id}/modsec/{sid}.conf;"]
    if pol.security_headers: L += [f'    add_header {h} "{v}" always;' for h, v in HEADERS]
    if tls and pol.hsts: L.append(f'    add_header Strict-Transport-Security "{HSTS}" always;')
    L.append("    error_page 429 @cg_429;")
    if pol.generic_errors: L += [f"    error_page {c} @cg_e{c};" for c in GENERIC]
    dry = ["        limit_req_dry_run on;   # monitoring: evaluate and log, do not enforce"] if pol.mode == "monitoring" else []
    for r in pol.rate_limits:
        lim = [f"        limit_req zone=cg_{sid}_{r['name']} burst={r['burst']} nodelay;", "        limit_req_status 429;"] + dry
        if r["path"] == "/": continue
        L += [f"    location ^~ {r['path']} {{"] + lim + ["        " + x for x in _proxy(site, pol)] + ["    }"]
    root_lim = [x for r in pol.rate_limits if r["path"] == "/" for x in
                [f"        limit_req zone=cg_{sid}_{r['name']} burst={r['burst']} nodelay;", "        limit_req_status 429;"] + dry]
    L += ["    location / {"] + root_lim + ["        " + x for x in _proxy(site, pol)] + ["    }"]
    L.append('    location @cg_429 { internal; add_header Retry-After 60 always; default_type text/plain; return 429 "Too many requests. Please slow down.\\n"; }')
    if pol.generic_errors:
        L += [f'    location @cg_e{c} {{ internal; default_type text/html; return {c} "<h1>{m}</h1><p>Please try again later.</p>"; }}' for c, m in GENERIC.items()]
    return "\n".join(L + ["}"])


def _site(release_id, root, site, pol, ver, tls, trusted, https_port):
    head = f"# site {site.site_id} policy v{ver} mode {pol.mode} release {release_id}\n"
    if not tls:
        return head + _server(release_id, root, site, pol, ver, False, trusted, https_port) + "\n"
    http = _server(release_id, root, site, pol, ver, False, trusted, https_port, redirect=(pol.https == "redirect"))
    return head + http + "\n" + _server(release_id, root, site, pol, ver, True, trusted, https_port) + "\n"
